using System.Collections.Immutable;
using System.Text;

namespace Mikita.Generation.Live;

public sealed class LiveSource
	(
		ImmutableArray<ILiveRelay> relays
	)
	: ILiveSource
	{
		public string Text
			{
				get
					{
						var text = new StringBuilder(Header);

						foreach (var relay in relays)
							text.Append(relay.Declaration);

						return text
							.Append(Registration)
							.ToString();
					}
			}

		private string Registration
			{
				get
					{
						var text = new StringBuilder(RegistrationHeader);

						foreach (var relay in relays)
							text.Append(relay.Registration);

						return text
							.Append(RegistrationFooter)
							.ToString();
					}
			}

		private const string Header
			= "// <auto-generated/>\n"
				+ "#nullable enable\n"
				+ "\n"
				+ "namespace Mikita.Subroutine.Relays;\n";

		private const string RegistrationHeader
			= "\ninternal static class LiveRegistration\n"
				+ "\t{\n"
				+ "\t\t[global::System.Runtime.CompilerServices"
				+ ".ModuleInitializer]\n"
				+ "\t\tinternal static void Register()\n"
				+ "\t\t\t{\n";

		private const string RegistrationFooter
			= "\t\t\t}\n"
				+ "\t}\n";
	}